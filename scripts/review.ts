/**
 * Review helper.
 *
 *   pnpm review
 *
 * Prints every article with its review status, tested devices and VERIFY markers, and writes:
 *   docs/verify-checklist.md  – VERIFY markers grouped by device or topic
 *   docs/images-checklist.md  – <ScreenshotSlot> entries still waiting for a real screenshot
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { indexArticles, ROOT, type IndexedArticle } from './lib/content-index';

interface Marker {
  article: string;
  file: string;
  text: string;
  group: string;
}

interface Slot {
  article: string;
  id: string;
  device: string;
  what: string;
  target: string;
}

const VERIFY_RE = /\{\/\*\s*VERIFY:\s*([\s\S]*?)\s*\*\/\}/g;
const SLOT_RE = /<ScreenshotSlot\s+([^>]*?)\/>/g;
const ATTR_RE = /(\w+)="([^"]*)"/g;

/** First match wins, so the most specific device comes first. */
const GROUPS: { name: string; test: (text: string, a: IndexedArticle) => boolean }[] = [
  { name: 'Legal review', test: (_t, a) => a.cluster === 'legal-streaming' },
  { name: 'Fire TV', test: (t) => /fire tv|fire os|vega os|\bstick\b/i.test(t) },
  { name: 'Android TV / Google TV', test: (t) => /android tv|google tv/i.test(t) },
  { name: 'Smart TV', test: (t) => /smart tv/i.test(t) },
  { name: 'Desktop computer', test: (t) => /desktop/i.test(t) },
  { name: 'Router and network', test: (t) => /\bdns\b|router|ethernet|wi-?fi|\bband\b/i.test(t) },
  { name: 'Store and downloads', test: (t) => /store|publisher|checksum|download/i.test(t) },
  { name: 'Player app', test: () => true },
];

function attrs(raw: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const m of raw.matchAll(ATTR_RE)) out[m[1]!] = m[2]!;
  return out;
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function main() {
  const articles = indexArticles({ includeDrafts: true });
  const markers: Marker[] = [];
  const slots: Slot[] = [];

  for (const a of articles) {
    const file = relative(ROOT, a.filePath).split('\\').join('/');
    for (const m of a.body.matchAll(VERIFY_RE)) {
      const text = m[1]!.replace(/\s+/g, ' ').trim();
      const group = GROUPS.find((g) => g.test(text, a))!.name;
      markers.push({ article: a.path, file, text, group });
    }
    for (const m of a.body.matchAll(SLOT_RE)) {
      const at = attrs(m[1]!);
      if (!at.id) continue;
      slots.push({
        article: a.path,
        id: at.id,
        device: at.device ?? '',
        what: at.what ?? '',
        target: `src/assets/articles/${a.slug}/${at.id}.webp`,
      });
    }
  }

  // Console summary
  console.log('Review status\n');
  for (const a of articles) {
    const status = String(a.frontmatter.reviewStatus ?? 'needs-human');
    const tested = (a.frontmatter.testedOn as string[] | undefined) ?? [];
    const count = markers.filter((m) => m.article === a.path).length;
    console.log(
      `${status.padEnd(12)} ${String(count).padStart(2)} VERIFY  testedOn: ${tested.length ? tested.join(', ') : '(none)'}  ${a.path}`,
    );
  }
  console.log(`\n${markers.length} VERIFY marker(s), ${slots.length} screenshot slot(s).`);

  // docs/verify-checklist.md
  const groups = GROUPS.map((g) => g.name).filter((name) => markers.some((m) => m.group === name));
  const verify = [
    '# Review checklist',
    '',
    'Generated by `pnpm review`. Do not edit by hand; edit the articles and run it again.',
    '',
    'An article moves to `reviewStatus: approved` only after every VERIFY marker below has been',
    'checked on the device or source named, the text corrected where needed, the marker removed,',
    'and `testedOn` filled in. `pnpm launch-check` fails while any marker or `needs-human` remains.',
    '',
    '## Articles',
    '',
    '| Article | Review status | Tested on | VERIFY |',
    '| --- | --- | --- | --- |',
    ...articles.map((a) => {
      const tested = (a.frontmatter.testedOn as string[] | undefined) ?? [];
      const count = markers.filter((m) => m.article === a.path).length;
      return `| ${a.path} | ${String(a.frontmatter.reviewStatus ?? 'needs-human')} | ${tested.length ? cell(tested.join(', ')) : 'none'} | ${count} |`;
    }),
    '',
    ...groups.flatMap((name) => {
      const items = markers.filter((m) => m.group === name);
      return [
        `## ${name} (${items.length})`,
        '',
        ...items.map((m) => `- [ ] ${cell(m.text)} — \`${m.file}\` (${m.article})`),
        '',
      ];
    }),
  ];

  // docs/images-checklist.md
  const images = [
    '# Screenshots to take',
    '',
    'Generated by `pnpm review`. Do not edit by hand.',
    '',
    'Rules: real screenshots only, taken on the device named, during hands-on testing. Never',
    'generate a screenshot of an app or a device interface. No logos, brand marks or recognisable',
    'people. WebP or AVIF, at most 150 KB (250 KB for a cover). A screenshot may only be published',
    'once the article lists the device in `testedOn`.',
    '',
    '| Article | Slot | Device | What to capture | Target file |',
    '| --- | --- | --- | --- | --- |',
    ...slots.map(
      (s) =>
        `| ${s.article} | ${cell(s.id)} | ${cell(s.device)} | ${cell(s.what)} | \`${s.target}\` |`,
    ),
    '',
    `${slots.length} slot(s).`,
    '',
  ];

  mkdirSync(join(ROOT, 'docs'), { recursive: true });
  writeFileSync(join(ROOT, 'docs', 'verify-checklist.md'), verify.join('\n'));
  writeFileSync(join(ROOT, 'docs', 'images-checklist.md'), images.join('\n'));
  console.log('Wrote docs/verify-checklist.md and docs/images-checklist.md');
}

main();
